import { spawn } from 'node:child_process'
import ytdlExec from 'youtube-dl-exec'

// `constants` exists at runtime but is missing from youtube-dl-exec's .d.ts.
const { YOUTUBE_DL_PATH } = (ytdlExec as unknown as { constants: { YOUTUBE_DL_PATH: string } })
  .constants
// A packaged app cannot exec from inside the asar; electron-builder unpacks this one.
const YTDLP = YOUTUBE_DL_PATH.replace('app.asar', 'app.asar.unpacked')

// Opus/WebM and AAC/M4A are both decodable by Chromium, so hand <audio> whichever
// YouTube has. The trailing `bestaudio` is a last resort that may not play.
const AUDIO_FORMAT = 'bestaudio[ext=webm]/bestaudio[ext=m4a]/bestaudio'

export interface Track {
  videoId: string
  title: string
  artist: string | null
  thumbnailUrl: string
  duration: number
}

/** Tidy up what people actually paste: whitespace, angle brackets, missing scheme. */
export function normalize(input: string): string | null {
  const s = String(input ?? '')
    .trim()
    .replace(/^<+|>+$/g, '')
    .trim()
  if (!s) return null
  if (/^https?:\/\//i.test(s)) return s
  if (/^(www\.|m\.|music\.)?(youtube\.com|youtube-nocookie\.com|youtu\.be)\//i.test(s)) {
    return `https://${s}`
  }
  return null
}

/**
 * 'playlist' | 'video' | 'search'. Anything that is not a recognized YouTube
 * video/playlist URL — free text, a foreign host, a truncated paste — is a search
 * term. A broken paste is better served by a search than an error.
 */
export function kindOf(url: string): 'playlist' | 'video' | 'search' {
  let u: URL
  try {
    u = new URL(url)
  } catch {
    return 'search'
  }
  if (!/(^|\.)(youtube\.com|youtube-nocookie\.com|youtu\.be)$/.test(u.hostname)) return 'search'

  // A watch URL carrying &list= is "video inside a playlist" — queue the whole list,
  // except autogenerated mixes (RD...), which are endless.
  const list = u.searchParams.get('list')
  if (list && !list.startsWith('RD')) return 'playlist'
  if (u.pathname === '/playlist') return 'search' // /playlist with no usable list=

  if (u.hostname === 'youtu.be' ? u.pathname.length > 1 : u.searchParams.get('v')) return 'video'
  if (u.pathname.startsWith('/shorts/') || u.pathname.startsWith('/live/')) return 'video'
  return 'search'
}

/**
 * The top result for a song title is often a 24/7 radio livestream or a
 * zero-duration premiere placeholder. Neither ever ends, so prefer a real track.
 */
export function pickResult<
  T extends { is_live?: boolean; live_status?: string; duration?: number }
>(results: T[]): T | null {
  const isLive = (r: T): boolean => Boolean(r?.is_live) || r?.live_status === 'is_live'
  return results.find((r) => !isLive(r) && (r?.duration ?? 0) > 0) ?? results[0] ?? null
}

/** yt-dlp's ERROR: line, stripped of its prefixes and made presentable. */
export function cleanError(stderr: string): string {
  const line = String(stderr)
    .split('\n')
    .find((l) => l.startsWith('ERROR:'))
  const msg = (line ?? '')
    .replace(/^ERROR:\s*/, '')
    .replace(/^\[[^\]]+\]\s*/, '')
    .replace(/^[\w-]{11}:\s*/, '')
    .trim()
  if (/age|sign in to confirm|inappropriate/i.test(msg)) return 'age-restricted'
  if (/private/i.test(msg)) return 'private'
  if (/not available in your country|geo|region/i.test(msg)) return 'region-locked'
  if (/unavailable|removed|terminated/i.test(msg)) return 'unavailable'
  if (/requested format/i.test(msg)) return 'no playable audio track'
  return msg.slice(0, 150) || 'could not be fetched'
}

/** Highest-resolution thumbnail we were given, else the one size YouTube always has. */
export function bestThumbnail(e: {
  id?: string
  thumbnails?: { url?: string; width?: number }[]
}): string {
  const list = e?.thumbnails
  if (Array.isArray(list) && list.length) {
    const best = list.reduce((a, b) => ((b?.width ?? 0) > (a?.width ?? 0) ? b : a))
    if (best?.url) return best.url
  }
  // hqdefault always exists; maxresdefault 404s on plenty of videos.
  return `https://i.ytimg.com/vi/${e?.id}/hqdefault.jpg`
}

function runYtdlp(args: string[], timeoutMs = 60_000): Promise<string> {
  return new Promise((res, rej) => {
    const child = spawn(YTDLP, args, { windowsHide: true })
    let out = ''
    let err = ''
    const timer = setTimeout(() => {
      child.kill('SIGKILL')
      rej(new Error('YouTube took too long to respond. Try again.'))
    }, timeoutMs)

    child.stdout.on('data', (c) => (out += c))
    child.stderr.on('data', (c) => (err += c))
    child.on('error', () => {
      clearTimeout(timer)
      rej(new Error('Could not run yt-dlp.'))
    })
    child.on('close', (code) => {
      clearTimeout(timer)
      if (code === 0) res(out)
      else rej(new Error(cleanError(err)))
    })
  })
}

interface Entry {
  id?: string
  title?: string
  duration?: number
  channel?: string
  uploader?: string
  thumbnails?: { url?: string; width?: number }[]
}

const toTrack = (e: Entry): Track => ({
  videoId: e.id ?? '',
  title: e.title ?? 'Unknown title',
  artist: e.channel ?? e.uploader ?? null,
  thumbnailUrl: bestThumbnail(e),
  duration: e.duration ?? 0
})

/** YouTube search results, in YouTube's own ranking. */
export async function search(query: string, limit = 12): Promise<Track[]> {
  const data = JSON.parse(
    await runYtdlp([
      `ytsearch${limit}:${query}`,
      '--dump-single-json',
      '--flat-playlist',
      '--no-warnings'
    ])
  )
  return (data.entries ?? []).filter((e: Entry) => e?.id).map(toTrack)
}

/** URL or search terms -> a queueable list. Throws user-facing messages. */
export async function resolve(input: string): Promise<{ name: string | null; tracks: Track[] }> {
  const query = String(input ?? '')
    .trim()
    .replace(/^<+|>+$/g, '')
    .trim()
  const url = normalize(query)
  const kind = kindOf(url ?? query)

  if (kind === 'search') {
    if (!query) throw new Error('Give me a YouTube link or something to search for.')
    const hit = pickResult(await search(query, 5))
    if (!hit) throw new Error(`No YouTube results for "${query}".`)
    return { name: null, tracks: [hit] }
  }

  const data = JSON.parse(
    await runYtdlp([
      url!,
      '--dump-single-json',
      '--flat-playlist',
      '--no-warnings',
      kind === 'playlist' ? '--yes-playlist' : '--no-playlist'
    ])
  )

  if (data._type === 'playlist') {
    const tracks: Track[] = (data.entries ?? [])
      .filter((e: Entry) => e?.id && !/^\[(deleted|private|unavailable)/i.test(e.title ?? ''))
      .map(toTrack)
    if (!tracks.length) throw new Error('That playlist is empty, private, or fully unavailable.')
    return { name: data.title ?? 'playlist', tracks }
  }
  return { name: null, tracks: [toTrack(data)] }
}

// googlevideo URLs are signed and short-lived, and resolving one costs a yt-dlp run.
const urlCache = new Map<string, { url: string; expires: number }>()

/** Direct CDN audio URL for a video. Cached until its signature expires. */
export async function audioUrl(videoId: string): Promise<string> {
  const hit = urlCache.get(videoId)
  if (hit && hit.expires > Date.now()) return hit.url

  const out = await runYtdlp([
    `https://www.youtube.com/watch?v=${videoId}`,
    '-f',
    AUDIO_FORMAT,
    '-g',
    '--no-playlist',
    '--no-warnings'
  ])
  const url = out.trim().split('\n')[0]
  if (!url) throw new Error('no playable audio track')
  // A live stream resolves to an HLS manifest, which Chromium's <audio> cannot
  // decode. Say so here, or the skip arrives as an unexplained "playback failed".
  if (url.includes('/manifest/hls')) throw new Error('livestream, not playable')

  const expire = Number(new URL(url).searchParams.get('expire')) * 1000
  urlCache.set(videoId, { url, expires: (expire || Date.now() + 3_600_000) - 60_000 })
  return url
}
